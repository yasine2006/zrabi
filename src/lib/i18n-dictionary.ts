// Helper function to get localized rug fields (FR / EN / AR)
export function getLocalizedRug(rug: any, locale: Locale) {
  return {
    name: locale === "ar" ? (rug.nameAr ?? rug.nameFr) : locale === "en" ? (rug.nameEn ?? rug.nameFr) : rug.nameFr,
    story: locale === "ar" ? (rug.storyAr ?? rug.storyFr) : locale === "en" ? (rug.storyEn ?? rug.storyFr) : rug.storyFr,
    material: locale === "ar" ? (rug.materialAr ?? rug.materialFr) : locale === "en" ? (rug.materialEn ?? rug.materialFr) : rug.materialFr,
    origin: locale === "ar" ? (rug.originAr ?? rug.originRegion) : locale === "en" ? (rug.originEn ?? rug.originRegion) : (rug.originFr ?? rug.originRegion),
    care: locale === "ar" ? (rug.careAr ?? "") : locale === "en" ? (rug.careEn ?? "") : (rug.careFr ?? ""),
  };
}